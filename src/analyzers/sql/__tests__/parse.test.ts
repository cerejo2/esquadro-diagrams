// The DDL parser on its own: what ends up in the intermediate model.
import { describe, expect, it } from 'vitest';
import { parseSql } from '../parse';

const parse = (sql: string) => parseSql([{ path: 'x.sql', content: sql }]);
const table = (sql: string, name: string) => {
  const t = parse(sql).tables.find((x) => x.name === name);
  if (!t) throw new Error(`no table ${name}`);
  return t;
};

describe('CREATE TABLE', () => {
  it('reads columns, types with arguments, NOT NULL and IDENTITY', () => {
    const t = table(
      `CREATE TABLE dbo.Conta (
         id INT IDENTITY(1,1) NOT NULL,
         saldo DECIMAL(10, 2) NULL DEFAULT (0),
         nota NVARCHAR(MAX),
         criada DATETIME2 NOT NULL CONSTRAINT DF_c DEFAULT SYSDATETIME()
       );`,
      'Conta',
    );
    expect(t.schema).toBe('dbo');
    expect(t.columns.map((c) => [c.name, c.type, c.notNull, c.identity])).toEqual([
      ['id', 'INT', true, true],
      ['saldo', 'DECIMAL(10,2)', false, false],
      ['nota', 'NVARCHAR(MAX)', false, false],
      ['criada', 'DATETIME2', true, false],
    ]);
  });

  it('reads multi-word types and stops at the constraints', () => {
    const t = table(
      `CREATE TABLE m (
         a INT UNSIGNED NOT NULL AUTO_INCREMENT,
         b double precision,
         c character varying(20) CHARACTER SET utf8 COLLATE utf8_bin,
         d timestamp with time zone DEFAULT now(),
         e integer[] NOT NULL,
         f ENUM('x', 'y') DEFAULT 'x' COMMENT 'state',
         g
       )`,
      'm',
    );
    expect(t.columns.map((c) => c.type ?? null)).toEqual([
      'INT UNSIGNED',
      'double precision',
      'character varying(20)',
      'timestamp with time zone',
      'integer[]',
      "ENUM('x','y')",
      null,
    ]);
    expect(t.columns[0]!.identity).toBe(true);
  });

  it('treats serial and GENERATED ... AS IDENTITY as identity columns', () => {
    const t = table(
      'CREATE TABLE p (a serial, b bigint GENERATED BY DEFAULT AS IDENTITY, c int GENERATED ALWAYS AS (a * 2) STORED)',
      'p',
    );
    expect(t.columns.map((c) => c.identity)).toEqual([true, true, false]);
  });

  it('reads column-level and table-level PRIMARY KEY, UNIQUE and FOREIGN KEY', () => {
    const t = table(
      `CREATE TABLE linha (
         enc INT NOT NULL REFERENCES encomenda(num) ON DELETE CASCADE,
         n SMALLINT NOT NULL,
         artigo CHAR(8) CONSTRAINT linha_artigo REFERENCES artigo ON UPDATE SET NULL,
         codigo CHAR(4) UNIQUE,
         CONSTRAINT pk_linha PRIMARY KEY CLUSTERED (enc, n DESC),
         UNIQUE (artigo, codigo),
         CONSTRAINT fk_x FOREIGN KEY (enc, n) REFERENCES outra (a, b) MATCH FULL,
         CHECK (n > 0)
       )`,
      'linha',
    );
    expect(t.pk).toEqual(['enc', 'n']);
    expect(t.uniques).toEqual([['codigo'], ['artigo', 'codigo']]);
    expect(t.fks.map((f) => [f.name ?? '', f.columns, f.refTable, f.refColumns, f.origin])).toEqual([
      ['', ['enc'], 'encomenda', ['num'], 'column'],
      ['linha_artigo', ['artigo'], 'artigo', [], 'column'],
      ['fk_x', ['enc', 'n'], 'outra', ['a', 'b'], 'table'],
    ]);
  });

  it('ignores MySQL KEY and INDEX lines but keeps a column called key', () => {
    const t = table(
      'CREATE TABLE k (`key` INT, `index` INT, KEY idx_a (`key`), INDEX (`index`), FULLTEXT KEY ft (`key`), UNIQUE KEY u (`index`))',
      'k',
    );
    expect(t.columns.map((c) => c.name)).toEqual(['key', 'index']);
    expect(t.uniques).toEqual([['index']]);
  });

  it('reads names with brackets, quotes, backticks, spaces and three-part schemas', () => {
    const r = parse(
      'CREATE TABLE [db].[dbo].[Order Lines] ([Line No] int); CREATE TABLE "a b" ("c d" int); CREATE TABLE `e` (`f` int)',
    );
    expect(r.tables.map((t) => [t.schema ?? '', t.name, t.columns[0]!.name])).toEqual([
      ['dbo', 'Order Lines', 'Line No'],
      ['', 'a b', 'c d'],
      ['', 'e', 'f'],
    ]);
  });

  it('skips table options after the closing parenthesis', () => {
    const r = parse(
      "CREATE TABLE a (x int) ENGINE=InnoDB DEFAULT CHARACTER SET = utf8mb4 COMMENT = 't';\nCREATE TABLE b (y int) WITHOUT ROWID;\nCREATE TABLE c (z int) ON [PRIMARY]",
    );
    expect(r.tables.map((t) => t.name)).toEqual(['a', 'b', 'c']);
    expect(r.diagnostics).toEqual([]);
  });

  it('records the lines of the table, its columns and its keys', () => {
    const t = table('\n\nCREATE TABLE t (\n  a int PRIMARY KEY,\n  b int REFERENCES u(x)\n);', 't');
    expect(t.ref).toEqual({ file: 'x.sql', line: 3, endLine: 6 });
    expect(t.columns.map((c) => c.ref.line)).toEqual([4, 5]);
    expect(t.pkRef?.line).toBe(4);
    expect(t.fks[0]!.ref.line).toBe(5);
  });

  it('skips temporary tables and CREATE TABLE ... AS SELECT with an info', () => {
    const r = parse('CREATE TEMPORARY TABLE t (a int); CREATE TABLE #tmp (a int); CREATE TABLE c AS SELECT 1 AS x;');
    expect(r.tables).toEqual([]);
    expect(r.diagnostics.map((d) => d.level)).toEqual(['info', 'info', 'info']);
  });

  it('warns about an unterminated table and keeps what it read', () => {
    const r = parse('CREATE TABLE t (a int, b int;\nCREATE TABLE u (c int);');
    expect(r.tables.map((t) => [t.name, t.columns.length])).toEqual([
      ['t', 2],
      ['u', 1],
    ]);
    expect(r.diagnostics.map((d) => d.level)).toEqual(['warn']);
  });

  it('the last of two definitions wins, with a warning', () => {
    const r = parse('CREATE TABLE t (a int);\nDROP TABLE t;\nCREATE TABLE t (b int);');
    expect(r.tables.map((t) => t.columns.map((c) => c.name))).toEqual([['b']]);
    expect(r.diagnostics.map((d) => [d.level, d.ref?.line])).toEqual([['warn', 3]]);
  });
});

describe('ALTER TABLE', () => {
  it('adds constraints and columns, several per statement, also before the CREATE', () => {
    const r = parse(`
      ALTER TABLE early ADD CONSTRAINT fk_e FOREIGN KEY (a) REFERENCES t(id);
      CREATE TABLE t (id int);
      CREATE TABLE early (a int);
      ALTER TABLE t ADD CONSTRAINT pk_t PRIMARY KEY (id), ADD UNIQUE (id);
      ALTER TABLE ONLY public.early ADD COLUMN IF NOT EXISTS b int NOT NULL REFERENCES t;
      ALTER TABLE early WITH NOCHECK ADD CONSTRAINT c1 CHECK (a > 0), CONSTRAINT fk_b FOREIGN KEY (b) REFERENCES t (id);
      ALTER TABLE early NOCHECK CONSTRAINT ALL;
      ALTER TABLE early DROP CONSTRAINT fk_e;
    `);
    const t = r.tables.find((x) => x.name === 't')!;
    const early = r.tables.find((x) => x.name === 'early')!;
    expect(t.pk).toEqual(['id']);
    expect(t.uniques).toEqual([['id']]);
    expect(early.columns.map((c) => [c.name, c.notNull])).toEqual([
      ['a', false],
      ['b', true],
    ]);
    expect(early.fks.map((f) => [f.name ?? '', f.columns.join(), f.origin])).toEqual([
      ['', 'b', 'alter'],
      ['fk_b', 'b', 'alter'],
      ['fk_e', 'a', 'alter'],
    ]);
    expect(r.diagnostics).toEqual([]);
  });

  it('warns when the table never appears', () => {
    const r = parse('ALTER TABLE ghost ADD CONSTRAINT f FOREIGN KEY (a) REFERENCES t(b);');
    expect(r.diagnostics.map((d) => [d.level, d.message])).toEqual([
      ['warn', 'ALTER TABLE ghost: no CREATE TABLE for it'],
    ]);
  });
});

describe('statements that are skipped', () => {
  it('skips USE, SET, PRINT, DROP, INSERT, UPDATE, DELETE, SELECT, EXEC and IF EXISTS silently', () => {
    const r = parse(`
      USE loja; SET NOCOUNT ON; PRINT 'x';
      IF EXISTS (SELECT * FROM sys.tables WHERE name = 'a') DROP TABLE a;
      INSERT INTO a VALUES (1, 'CREATE TABLE fake (x int)'); UPDATE a SET b = 1; DELETE FROM a; SELECT 1;
      EXEC sp_help; EXECUTE ('CREATE TABLE fake2 (x int)');
      CREATE TABLE a (b int);
    `);
    expect(r.tables.map((t) => t.name)).toEqual(['a']);
    expect(r.diagnostics).toEqual([]);
  });

  it('skips procedures, functions and triggers with an info that names them', () => {
    const r = parse(`
      CREATE PROCEDURE dbo.p @x int AS BEGIN SELECT 1; IF @x > 0 BEGIN SELECT 2; END; END;
      CREATE OR REPLACE FUNCTION f() RETURNS int LANGUAGE plpgsql AS $$ BEGIN CREATE TABLE no (a int); RETURN 1; END $$;
      CREATE TRIGGER trg AFTER INSERT ON t BEGIN UPDATE t SET a = CASE WHEN a > 0 THEN 1 ELSE 0 END; END;
      CREATE TABLE yes (a int);
    `);
    expect(r.tables.map((t) => t.name)).toEqual(['yes']);
    expect(r.diagnostics.map((d) => d.message)).toEqual([
      'skipped procedure p',
      'skipped function f',
      'skipped trigger trg',
    ]);
  });

  it('a T-SQL procedure in a script with GO lasts until the next GO, semicolons included', () => {
    const r = parse('CREATE PROC p AS\nSELECT 1;\nCREATE TABLE inside (a int);\nGO\nCREATE TABLE outside (a int)\nGO');
    expect(r.tables.map((t) => t.name)).toEqual(['outside']);
  });

  it('a MySQL procedure between DELIMITER lines is skipped whole', () => {
    const r = parse(
      'DELIMITER $$\nCREATE PROCEDURE p()\nBEGIN\n  IF 1 THEN SELECT 1; END IF;\n  CREATE TABLE inside (a int);\nEND $$\nDELIMITER ;\nCREATE TABLE outside (a int);',
    );
    expect(r.tables.map((t) => t.name)).toEqual(['outside']);
  });

  it('reads the statement after an IF condition, also inside BEGIN ... END and after ELSE', () => {
    const r = parse(`
      IF OBJECT_ID('a') IS NULL
      BEGIN
        CREATE TABLE a (x int)
      END
      ELSE CREATE TABLE b (y int)
      IF NOT EXISTS (SELECT 1 FROM t) CREATE TABLE c (z int)
    `);
    expect(r.tables.map((t) => t.name)).toEqual(['a', 'b', 'c']);
  });

  it('finds statement boundaries without semicolons (old T-SQL)', () => {
    const r = parse(
      'CREATE TABLE a (x int)\nINSERT INTO a VALUES (1)\nCREATE TABLE b (y int REFERENCES a(x))\nALTER TABLE a ADD PRIMARY KEY (x)\nSELECT * FROM a',
    );
    expect(r.tables.map((t) => [t.name, t.pk.join(), t.fks.length])).toEqual([
      ['a', 'x', 0],
      ['b', '', 1],
    ]);
  });

  it('leaves an info for statements it does not know, and carries on', () => {
    const r = parse('FROBNICATE everything;\nCREATE TABLE a (x int);');
    expect(r.tables.map((t) => t.name)).toEqual(['a']);
    expect(r.diagnostics.map((d) => [d.level, d.message, d.ref?.line])).toEqual([
      ['info', 'skipped an unrecognised statement "FROBNICATE"', 1],
    ]);
  });
});

describe('CREATE VIEW', () => {
  it('collects the tables in FROM and JOIN, with aliases, comma joins and nested joins', () => {
    const r = parse(`
      CREATE VIEW v AS
      SELECT * FROM a x, dbo.b AS y
        LEFT JOIN (c INNER JOIN [d e] de ON de.k = c.k) ON y.k = c.k
        WHERE x.k IN (SELECT k FROM f);
      CREATE OR REPLACE VIEW w (n) AS SELECT count(*) FROM a GROUP BY 1;
    `);
    expect(r.views.map((v) => [v.name, v.deps.map((d) => d.name)])).toEqual([
      ['v', ['a', 'b', 'c', 'd e', 'f']],
      ['w', ['a']],
    ]);
  });
});

describe('several files', () => {
  it('reads files in path order and links ALTERs across them', () => {
    const r = parseSql([
      { path: 'b/fks.sql', content: 'ALTER TABLE t ADD FOREIGN KEY (u_id) REFERENCES u(id);' },
      { path: 'a/tables.sql', content: 'CREATE TABLE u (id int PRIMARY KEY); CREATE TABLE t (u_id int);' },
    ]);
    expect(r.tables.map((t) => t.name)).toEqual(['u', 't']);
    expect(r.tables[1]!.fks[0]!.ref.file).toBe('b/fks.sql');
  });
});
